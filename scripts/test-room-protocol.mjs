// test-room-protocol: end-to-end proof, over real sockets against a real spawned
// relay, of the two things a separately-deployed client/server pair needs:
//
//   1. a COMPATIBILITY HANDSHAKE  (CODEX_REVIEW COR-9)
//   2. a GRACEFUL SHUTDOWN        (CODEX_REVIEW SEC-6)
//
//   node scripts/test-room-protocol.mjs        (exit 0 = both behave)
//
// It binds ports (8894/8895 for the relay, 8896/8897 for the in-process log
// server), so it lives in `npm run test:servers`, never in the pure `npm test`
// tier. The PURE half of the same work — the version rules themselves and the
// client's reconnect gate — is in scripts/test-net.mjs.
//
// WHY THIS EXISTS AT ALL. `npm run deploy` publishes dist/; `npm run deploy-room`
// ships server/* and src/net/NetProtocol.js. Two commands, so a skewed pair is
// the NORMAL state during a rollout — and on 2026-08-03 the live relay had been
// running a two-month-old Hub for five days with nothing but "multiplayer feels
// broken" to show for it. Skew used to be invisible: decode() drops what it does
// not understand and both ends fall quiet.
//
// EVERY behavioural claim below is asserted as a PAIR — the same action against a
// server where the feature is enabled and against one where it is turned off —
// because a suite that only ever sees the good outcome cannot tell "the feature
// works" from "nothing works". The shutdown control is ROOM_SHUTDOWN_GRACE_MS=0,
// which is the documented pre-fix behaviour (exit at once, every peer sees 1006).

import { spawn } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join as pathJoin } from 'node:path';
import { writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { WebSocket } from 'ws';
import { encode, decode, MSG, makeJoin, PROTOCOL_VERSION, PROTOCOL_CLOSE_CODE } from '../src/net/NetProtocol.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SERVER = pathJoin(ROOT, 'server', 'room-server.mjs');
const PORT_A = 8894;
const PORT_B = 8895;

let passed = 0, failed = 0;
const ok = (cond, msg) => {
  if (cond) { passed++; console.log(`  ok   ${msg}`); }
  else { failed++; console.error(`  FAIL ${msg}`); }
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// --- server harness --------------------------------------------------------
//
// The relay is started through a tiny generated WRAPPER rather than directly,
// for one reason: Windows has no real SIGTERM. libuv maps
// `process.kill(pid,'SIGTERM')` to TerminateProcess, which destroys the child
// outright — it would "prove" a 1006 whether or not a handler exists, i.e. it
// would make the whole shutdown section unfalsifiable on this machine. Node CAN
// *listen* for 'SIGTERM' on Windows, so the wrapper re-raises the signal
// in-process when this test nudges its stdin. On POSIX a genuine signal is sent
// instead and the wrapper is inert, so the same file tests the real thing there.
const WRAPPER = pathJoin(tmpdir(), `libretrowebxr-room-signal-${process.pid}.mjs`);
writeFileSync(WRAPPER, `// generated by scripts/test-room-protocol.mjs — safe to delete
process.stdin.setEncoding('utf8');
// UNREF the stdin handle. A flowing stdin is an active libuv handle, and leaving
// it referenced would keep the child's event loop alive after a perfectly clean
// drain — i.e. THIS HARNESS would be the reason the process failed to exit, and
// the shutdown assertions would be measuring the wrapper instead of the server.
if (typeof process.stdin.unref === 'function') process.stdin.unref();
process.stdin.on('data', (s) => {
  for (const line of String(s).split('\\n')) {
    const t = line.trim();
    if (t === 'SIGTERM' || t === 'SIGINT') process.emit(t);
  }
});
await import(${JSON.stringify(pathToFileURL(SERVER).href)});
`);

function startServer(port, env = {}) {
  const child = spawn(process.execPath, [WRAPPER], {
    cwd: ROOT,
    stdio: ['pipe', 'pipe', 'pipe'],
    env: { ...process.env, PORT: String(port), LOG_PORT: String(port === PORT_A ? 8896 : 8897), ...env },
  });
  const out = [];
  let exited = null;
  let exitedAt = null;
  child.stdout.on('data', (d) => out.push(String(d)));
  child.stderr.on('data', (d) => out.push(String(d)));
  child.on('exit', (code) => { exited = code ?? -1; exitedAt = Date.now(); });
  const ready = new Promise((resolve, reject) => {
    const t = setTimeout(() => reject(new Error(`server :${port} did not report listening\n${out.join('')}`)), 8000);
    const tick = setInterval(() => {
      if (out.join('').includes(`listening on :${port}`)) { clearInterval(tick); clearTimeout(t); resolve(); }
      if (exited != null) { clearInterval(tick); clearTimeout(t); reject(new Error(`server :${port} exited ${exited}\n${out.join('')}`)); }
    }, 40);
  });
  return {
    child, ready,
    get exited() { return exited; },
    get exitedAt() { return exitedAt; },
    log: () => out.join(''),
    /** Deliver SIGTERM/SIGINT the way this platform actually can (see above). */
    signal(sig = 'SIGTERM') {
      if (process.platform === 'win32') child.stdin.write(`${sig}\n`);
      else child.kill(sig);
    },
    /** Resolve with ms-to-exit, or null if it was still running after `ms`. */
    waitExit(ms = 4000) {
      const t0 = Date.now();
      return new Promise((resolve) => {
        if (exited != null) return resolve(0);
        const timer = setTimeout(() => resolve(null), ms);
        child.once('exit', () => { clearTimeout(timer); resolve(Date.now() - t0); });
      });
    },
  };
}

const stop = (s) => new Promise((r) => {
  if (!s || s.exited != null) return r();
  s.child.once('exit', () => r());
  s.child.kill();                       // by PID — never by process name
  setTimeout(r, 1500);
});

// --- client harness (same shape as scripts/test-room-limits.mjs) ------------

function client(port, room, name) {
  const ws = new WebSocket(`ws://127.0.0.1:${port}/?room=${encodeURIComponent(room)}`);
  const msgs = [];
  const waiters = [];
  const c = {
    ws, name, msgs, selfId: null, closeCode: null, closeReason: '',
    open: () => new Promise((resolve, reject) => { ws.once('open', resolve); ws.once('error', reject); }),
    send: (m) => { try { ws.send(encode(m)); } catch { /* closed */ } },
    waitFor: (pred, ms = 2000) => new Promise((resolve, reject) => {
      const hit = msgs.find(pred);
      if (hit) return resolve(hit);
      const w = { pred, resolve };
      waiters.push(w);
      setTimeout(() => {
        const i = waiters.indexOf(w);
        if (i >= 0) { waiters.splice(i, 1); reject(new Error(`${name}: timeout waiting`)); }
      }, ms);
    }),
    // { code:null } means STILL OPEN after `ms`: a server without the feature
    // never closes anything, and that must read as a failed assertion rather
    // than a hung suite.
    closed: (ms = 4000) => new Promise((resolve) => {
      if (ws.readyState === ws.CLOSED) return resolve({ code: c.closeCode, reason: c.closeReason });
      const t = setTimeout(() => resolve({ code: null, reason: 'still open' }), ms);
      ws.once('close', (code, reason) => { clearTimeout(t); resolve({ code, reason: String(reason || '') }); });
    }),
  };
  ws.on('message', (data) => {
    const m = decode(data.toString());
    if (!m) return;
    msgs.push(m);
    if (m.type === MSG.HELLO) c.selfId = m.selfId;
    for (let i = waiters.length - 1; i >= 0; i--) {
      if (waiters[i].pred(m)) { waiters[i].resolve(m); waiters.splice(i, 1); }
    }
  });
  ws.on('close', (code, reason) => { c.closeCode = code; c.closeReason = String(reason || ''); });
  ws.on('error', () => { /* close/observed by the assertions */ });
  return c;
}

async function join(port, room, name) {
  const c = client(port, room, name);
  await c.open();
  await c.waitFor((m) => m.type === MSG.HELLO);
  return c;
}

// ---------------------------------------------------------------------------

async function main() {
  let s = null;

  // ============================= 1. compatibility handshake (COR-9) =========
  console.log('\n--- protocol handshake over a real socket (COR-9) ---');
  s = startServer(PORT_A);
  await s.ready;
  {
    // The server states its version to every client, unprompted.
    const a = await join(PORT_A, 'proto', 'A');
    const hello = a.msgs.find((m) => m.type === MSG.HELLO);
    ok(hello.v === PROTOCOL_VERSION,
      `HELLO announces the server protocol version ("${hello.v}") — an OLD server is detectable client-side`);

    // CONTROL: the version the shipped client actually sends is accepted, and the
    // JOIN is relayed to the room as before. Without this line, every rejection
    // below could equally mean "the server refuses all JOINs".
    const b = await join(PORT_A, 'proto', 'B');
    b.send(makeJoin({ nick: 'Bob' }));
    const relayed = await a.waitFor((m) => m.type === MSG.JOIN && m.nick === 'Bob');
    ok(relayed.v === PROTOCOL_VERSION, 'control: a current client is accepted and its JOIN is relayed, version and all');
    ok(b.ws.readyState === b.ws.OPEN, 'control: and its socket stays open');

    // CONTROL: a different MINOR is compatible — additive protocol changes must
    // not disconnect anyone, or every deploy becomes an outage.
    const minor = client(PORT_A, 'proto', 'MINOR');
    await minor.open();
    minor.send({ type: MSG.JOIN, nick: 'Minor', color: '#fff', v: `${PROTOCOL_VERSION.split('.')[0]}.9999` });
    await sleep(200);
    ok(minor.ws.readyState === minor.ws.OPEN, 'control: a NEWER minor version of the same major is accepted');

    // A pre-COR-9 client announces nothing at all. It MUST be accepted — the app
    // deployed on dionysus.dk today sends no version, and a relay update that
    // bricked it would turn a routine deploy into an outage — but it is logged.
    const legacy = client(PORT_A, 'proto', 'LEGACY');
    await legacy.open();
    legacy.send({ type: MSG.JOIN, nick: 'Legacy', color: '#fff' });   // no `v`
    await sleep(250);
    ok(legacy.ws.readyState === legacy.ws.OPEN, 'a legacy client (no version) is ACCEPTED, not bricked');
    ok(/announced no protocol version/.test(s.log()), 'and the skew is logged for the operator');
    const legacyLines = (s.log().match(/announced no protocol version/g) || []).length;
    legacy.send({ type: MSG.JOIN, nick: 'Legacy', color: '#fff' });
    legacy.send({ type: MSG.JOIN, nick: 'Legacy', color: '#fff' });
    await sleep(200);
    ok((s.log().match(/announced no protocol version/g) || []).length === legacyLines,
      'logged ONCE per socket — a client spamming JOIN cannot spam the journal');

    // THE FIX: an incompatible MAJOR is refused with 4010 and a readable reason.
    const bad = client(PORT_A, 'proto', 'BAD');
    await bad.open();
    bad.send({ type: MSG.JOIN, nick: 'Bad', color: '#fff', v: '99.0' });
    const closed = await bad.closed();
    ok(closed.code === PROTOCOL_CLOSE_CODE, `an incompatible MAJOR is closed with ${PROTOCOL_CLOSE_CODE} (got ${closed.code})`);
    ok(/99\.0/.test(closed.reason) && /1\./.test(closed.reason),
      `and the reason names both versions — "${closed.reason}"`);

    // A hostile version string must not be able to hurt the relay: the close
    // reason is capped at 123 bytes by the WebSocket spec, and building an
    // over-long one throws inside the send path.
    const hostile = client(PORT_A, 'proto', 'HOSTILE');
    await hostile.open();
    hostile.send({ type: MSG.JOIN, nick: 'X', color: '#fff', v: '9'.repeat(5000) });
    const hClosed = await hostile.closed();
    ok(hClosed.code === PROTOCOL_CLOSE_CODE, 'a 5000-char version string is refused, not crashed on');
    const after = await join(PORT_A, 'proto', 'AFTER');
    ok(!!after.selfId, 'control: the relay is still serving afterwards (the refusal did not take it down)');

    for (const c of [a, b, minor, legacy, after]) c.ws.close();
    await sleep(100);
  }

  // ---- 1b. `v` OF ANY TYPE GETS A VERDICT, NEVER SILENCE (2026-08-15) -------
  //
  // Regression guard. Between 2026-08-14 and 2026-08-15, NetProtocol.validate()
  // rejected a JOIN whose `v` was not a string. decode() turns that into null and
  // room-server.mjs's handler does `if (!msg) { ws._invalid++; return; }` — so a
  // peer announcing `v: 2` was never closed, never refused, and never relayed to
  // the room: it sat on an open socket, invisible to everyone, with one line in
  // the journal about an "undecodable message". That silent drop is precisely the
  // failure COR-9 exists to remove, so it is asserted at the SOCKET here rather
  // than at validate()'s return value.
  //
  // Every case is asserted as a pair: what happened to the joiner's socket, AND
  // whether a WATCHER already in the room saw the roster JOIN.
  console.log('\n--- every shape of `v` gets a verdict, never silence (COR-9) ---');
  {
    const CASES = [
      { label: 'absent',      body: {},                    accept: true  },
      { label: 'null',        body: { v: null },           accept: true  },
      { label: "'' (empty)",  body: { v: '' },             accept: true  },
      { label: 'current',     body: { v: PROTOCOL_VERSION }, accept: true },
      { label: '2 (number)',  body: { v: 2 },              accept: false },
      { label: '{major:2}',   body: { v: { major: 2 } },   accept: false },
      { label: "'garbage'",   body: { v: 'garbage' },      accept: false },
    ];
    for (const c of CASES) {
      const room = `vtype-${CASES.indexOf(c)}`;
      const watcher = await join(PORT_A, room, `W-${c.label}`);
      const peer = client(PORT_A, room, `P-${c.label}`);
      await peer.open();
      const nick = `N${CASES.indexOf(c)}`;
      peer.send({ type: MSG.JOIN, nick, color: '#fff', ...c.body });
      if (c.accept) {
        // ACCEPTED: socket stays open AND the room is told the peer exists.
        const relayed = await watcher.waitFor((m) => m.type === MSG.JOIN && m.nick === nick, 2000)
          .catch(() => null);
        ok(!!relayed, `v=${c.label}: the JOIN is relayed to the room (the peer is visible)`);
        ok(peer.ws.readyState === peer.ws.OPEN, `v=${c.label}: and its socket stays open`);
      } else {
        // REFUSED: closed with 4010 and a reason — never left connected-and-mute.
        const closed = await peer.closed(3000);
        ok(closed.code === PROTOCOL_CLOSE_CODE,
          `v=${c.label}: refused with ${PROTOCOL_CLOSE_CODE}, not silently dropped (got ${closed.code})`);
        // The reason must SAY something, and specifically say what: `closed()`
        // reports "still open" when nothing was ever closed, so a bare
        // length-is-nonzero check would pass on the very silence being tested.
        ok(/incompatible|unparseable/.test(closed.reason),
          `v=${c.label}: and the close carries a diagnosable reason ("${closed.reason}")`);
        await sleep(150);
        // Complementary, not independent: a SILENTLY DROPPED peer is also absent
        // from the roster, so this line alone cannot tell refusal from silence —
        // the 4010 assertion above is what does that. It is here because
        // "connected but invisible" was the actual reported symptom.
        ok(!watcher.msgs.some((m) => m.type === MSG.JOIN && m.nick === nick),
          `v=${c.label}: and the refused peer never appears on anyone's roster`);
      }
      try { peer.ws.close(); } catch { /* already closed */ }
      watcher.ws.close();
      await sleep(50);
    }
    // The relay survived all of it — a junk `v` must not be a way to kill it.
    const alive = await join(PORT_A, 'vtype-after', 'ALIVE');
    ok(!!alive.selfId, 'control: the relay is still serving after every junk version');
    alive.ws.close();
    await sleep(100);
  }
  await stop(s);

  // ============================= 2. graceful shutdown (SEC-6) ===============
  //
  // Before this, SIGTERM/SIGINT had no handler at all, so `systemctl restart` —
  // which `npm run deploy-room` runs on every server update — destroyed every
  // socket mid-frame. Peers saw a bare 1006, indistinguishable from a crash or a
  // Wi-Fi drop, and the room kept their ghosts for a heartbeat period.
  console.log('\n--- SIGTERM drains sockets with 1001 + a reason (SEC-6) ---');
  {
    s = startServer(PORT_A);
    await s.ready;
    const a = await join(PORT_A, 'bye', 'A');
    const b = await join(PORT_A, 'bye', 'B');
    s.signal('SIGTERM');
    const [ca, cb] = await Promise.all([a.closed(), b.closed()]);
    ok(ca.code === 1001 && cb.code === 1001, `every live socket is closed with 1001 "going away" (got ${ca.code}/${cb.code})`);
    ok(/restarting/i.test(ca.reason), `and carries a human-readable reason — "${ca.reason}"`);
    const ms = await s.waitExit(4000);
    ok(ms !== null, `the process exits instead of hanging (${ms}ms)`);
    ok(ms !== null && ms < 2500, `and exits on the DRAIN, not on the forced-exit timer (${ms}ms < 5000ms grace)`);
    ok(!/forcing exit/.test(s.log()), 'the forced-exit path was not needed for a clean drain');
    await stop(s);
  }

  // NEGATIVE CONTROL. ROOM_SHUTDOWN_GRACE_MS=0 is the documented pre-fix
  // behaviour — no drain, exit immediately. The identical client, the identical
  // signal, and the 1001 above becomes the 1006 that used to be all anyone got.
  console.log('\n--- NEGATIVE CONTROL: ROOM_SHUTDOWN_GRACE_MS=0 (the pre-fix drop) ---');
  {
    s = startServer(PORT_B, { ROOM_SHUTDOWN_GRACE_MS: '0' });
    await s.ready;
    const a = await join(PORT_B, 'bye', 'A');
    s.signal('SIGTERM');
    const ca = await a.closed();
    ok(ca.code === 1006, `with the drain disabled the SAME client sees a bare 1006 (got ${ca.code})`);
    ok(!/draining/.test(s.log()), 'and nothing was drained');
    ok(await s.waitExit(4000) !== null, 'the process still exits (it just takes everyone down with it)');
    await stop(s);
  }

  // The forced-exit timer. A peer that never answers the close frame keeps `ws`
  // waiting 30 s by default — long enough for systemd to give up and SIGKILL the
  // unit, which is the hang the timer exists to prevent.
  //
  // This is also where idempotency is asserted, for a mundane reason: a CLEAN
  // drain exits in ~10 ms, so a second signal sent after it would race the exit
  // and the assertion would be flaky rather than meaningful. Here the process is
  // deliberately alive for the whole grace window, so the second signal is
  // guaranteed to be delivered to a process that is already shutting down.
  console.log('\n--- a socket that never answers cannot hang the unit (+ idempotency) ---');
  {
    s = startServer(PORT_A, { ROOM_SHUTDOWN_GRACE_MS: '800' });
    await s.ready;
    const a = await join(PORT_A, 'stuck', 'A');
    // Stop reading from the TCP socket: the close frame arrives but is never
    // parsed and never echoed, so the server's side of the connection stays open.
    a.ws._socket.pause();
    s.signal('SIGTERM');
    await sleep(200);
    // A second signal (systemd escalating, a human hitting Ctrl-C twice, a SIGINT
    // racing a SIGTERM) must NOT re-run the drain or arm a second forced timer.
    s.signal('SIGTERM');
    await sleep(100);
    ok((s.log().match(/draining \d+ socket/g) || []).length === 1,
      'the drain ran exactly ONCE despite two signals');
    ok(/already shutting down/.test(s.log()), 'and the second signal is explicitly reported as ignored');
    const ms = await s.waitExit(6000);
    ok(ms !== null, `the process still exits with a stuck socket (${ms}ms)`);
    ok(ms !== null && ms < 4000, 'and within the forced-exit grace, not ws\'s 30s close timeout');
    ok(/forcing exit/.test(s.log()), 'the forced-exit path is what got it out, and says so');
    try { a.ws.terminate(); } catch { /* gone */ }
    await stop(s);
  }

  // SIGINT (Ctrl-C in a dev terminal) takes the same path.
  console.log('\n--- SIGINT drains the same way ---');
  {
    s = startServer(PORT_B);
    await s.ready;
    const a = await join(PORT_B, 'bye', 'A');
    s.signal('SIGINT');
    const ca = await a.closed();
    ok(ca.code === 1001, `SIGINT drains with 1001 too (got ${ca.code})`);
    ok(await s.waitExit(4000) !== null, 'and exits');
    await stop(s);
  }
}

main()
  .catch((e) => { failed++; console.error('  FAIL harness:', e?.stack || e); })
  .finally(async () => {
    try { rmSync(WRAPPER, { force: true }); } catch { /* fine */ }
    console.log(`\n${passed} passed, ${failed} failed`);
    process.exit(failed ? 1 : 0);
  });
